#!/bin/bash
# Запуск всех тестов: параллельно для обычных, последовательно для cache_sensitive

echo "========================================"
echo "🚀 ЭТАП 1: Обычные тесты (параллельно)"
echo "========================================"
pytest tests/ -n auto -q -m "not cache_sensitive"
RESULT1=$?

echo ""
echo "========================================"
echo "🚀 ЭТАП 2: Cache-sensitive тесты (последовательно)"
echo "========================================"
pytest tests/ -q -m cache_sensitive -o addopts=""
RESULT2=$?

echo ""
echo "========================================"
echo "📊 РЕЗУЛЬТАТ:"
echo "========================================"
if [ $RESULT1 -eq 0 ] && [ $RESULT2 -eq 0 ]; then
    echo "✅ Все тесты пройдены успешно!"
    exit 0
else
    echo "❌ Есть падения"
    exit 1
fi
